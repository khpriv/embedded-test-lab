static void oled_commands(const uint8_t *commands, uint16_t count)
{
    uint8_t buffer[32];

    buffer[0] = 0x00;

    for (uint16_t i = 0; i < count; i++)
    {
        buffer[i + 1] = commands[i];
    }

    HAL_I2C_Master_Transmit(
        oled_i2c,
        SSD1306_ADDR,
        buffer,
        count + 1,
        100
    );
}


void SSD1306_Init(I2C_HandleTypeDef *hi2c)
{
    oled_i2c = hi2c;

    const uint8_t init_sequence[] = {
        0xAE,

        0xD5, 0x80,
        0xA8, 0x3F,
        0xD3, 0x00,
        0x40,

        0x8D, 0x14,

        0x20, 0x00,

        0xA1,
        0xC8,

        0xDA, 0x12,
        0x81, 0xCF,
        0xD9, 0xF1,
        0xDB, 0x40,

        0xA4,
        0xA6,
        0xAF
    };

    oled_commands(init_sequence, sizeof(init_sequence));
}


void SSD1306_AllPixelsOn(void)
{
    const uint8_t command[] = {0xA5};
    oled_commands(command, 1);
}


void SSD1306_AllPixelsOff(void)
{
    const uint8_t command[] = {0xA4};
    oled_commands(command, 1);
}


void SSD1306_Clear(void)
{
    memset(framebuffer, 0, sizeof(framebuffer));
}

void SSD1306_DrawPixel(uint8_t x, uint8_t y, uint8_t on)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT)
    {
        return;
    }

    uint16_t index =
        x + (y / 8) * SSD1306_WIDTH;

    uint8_t mask = 1 << (y % 8);

    if (on)
    {
        framebuffer[index] |= mask;
    }
    else
    {
        framebuffer[index] &= ~mask;
    }
}

static void oled_data(
    const uint8_t *data,
    uint16_t length)
{
    uint8_t buffer[129];

    while (length > 0)
    {
        uint16_t chunk =
            length > 128 ? 128 : length;

        buffer[0] = 0x40;

        memcpy(
            &buffer[1],
            data,
            chunk
        );

        HAL_I2C_Master_Transmit(
            oled_i2c,
            SSD1306_ADDR,
            buffer,
            chunk + 1,
            100
        );

        data += chunk;
        length -= chunk;
    };
}

void SSD1306_UpdateScreen(void)
{
    const uint8_t addressing[] = {
        0x21, 0, 127,   // columns 0..127
        0x22, 0, 7      // pages 0..7
    };

    oled_commands(
        addressing,
        sizeof(addressing)
    );

    oled_data(
        framebuffer,
        sizeof(framebuffer)
    );
}

static const Glyph8x12 *find_glyph(char c)
{
    for (size_t i = 0;
         i < sizeof(font8x12) / sizeof(font8x12[0]);
         i++)
    {
        if (font8x12[i].character == c)
        {
            return &font8x12[i];
        }
    }

    return NULL;
}

void SSD1306_SetCursor(uint8_t x, uint8_t y)
{
    cursor_x = x;
    cursor_y = y;
}


void SSD1306_WriteChar(char c)
{
    const Glyph8x12 *glyph = find_glyph(c);

    if (glyph == NULL)
    {
        cursor_x += 8;
        return;
    }

    for (uint8_t y = 0; y < 12; y++)
    {
        for (uint8_t x = 0; x < 8; x++)
        {
            if (glyph->rows[y] & (0x80 >> x))
            {
                SSD1306_DrawPixel(
                    cursor_x + x,
                    cursor_y + y,
                    1
                );
            }
        }
    }

    cursor_x += 8;
}


void SSD1306_WriteString(const char *text)
{
    while (*text)
    {
        SSD1306_WriteChar(*text++);
    }
}
